"""Bundle the radio recovery page's code and matching firmware pair.

The classic script also works beside a local file:// HTML page; it performs no
fetch and embeds only build artifacts, never device captures or calibration.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import sys

HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'tools'))
from fm1_recover import Package
from fm1_install import LOADER_MARK

MODULES=[
    ('fm1backup.js',['bkPack','bkUnpack']),
    ('fm1pkg.js',['Package','logicalImage','sha256hex']),
    ('fm1ota.js',['Updater','pack7','unpack7','MELODEE_LOADER']),
    ('install/keepalive.js',['hold']),
    ('install/transfer.js',['SteadyUpdater']),
    ('install/progress.js',['progressModel','remaining','releaseVersion']),
    ('install/fakefm1.js',['fakeAccess']),
    ('blecalibration.js',['extractCalibration','readCalibration','calibrationFile','crc16',
        'calibrationStatus','calibrationPreflight','restoreCalibration','generateCalibration','recoverDevice','helperTrace',
        'helperState','helperResult','HELPER_PRODUCT']),
    ('ble-calibration-packages.js',['calibrationPackages']),
    ('ble-calibration-demo.js',['demoSetup']),
]

def strip(source):
    source=re.sub(r'^import[\s\S]*?from\s+[\'"][^\'"]+[\'"];\s*','',source,flags=re.M)
    return re.sub(r'^export\s+','',source,flags=re.M)

def bundle_package(path,helper):
    path=Path(path);data=path.read_bytes();pkg=Package(path)
    if (pkg.product!='FM-1_998' if helper else not re.fullmatch(r'FM-1_9\d+',pkg.product) or pkg.product=='FM-1_998'):
        raise ValueError('Not the expected calibration helper / Melodee pair')
    if LOADER_MARK not in data:raise ValueError('Recovery requires the Melodee update loader')
    return dict(product=pkg.product,bytes=len(data),sha256=hashlib.sha256(data).hexdigest(),
                data=base64.b64encode(data).decode())

def write_bundle(output,firmware=None,helper=None,version='development BLE build'):
    if bool(firmware)!=bool(helper):raise ValueError('Bundle both firmware images together')
    bundle=None
    if firmware:
        bundle=dict(schema=1,version=version,helper=bundle_package(helper,True),firmware=bundle_package(firmware,False))
    parts=['// Generated by make_ble_calibration.py; source notices are retained below.\n',
        'globalThis.MELODEE_CALIBRATION_BUNDLE='+json.dumps(bundle,separators=(',',':'))+';\n',
        '(()=>{\n"use strict";\n']
    for path,exports in MODULES:
        names=','.join(exports)
        parts.append('const {'+names+'}=(()=>{\n'+strip((HERE/path).read_text())+'\nreturn {'+names+'};\n})();\n')
    parts.append(strip((HERE/'ble-calibration-page.js').read_text())+'\n})();\n')
    output=Path(output);output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(''.join(parts))
    return bundle

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('firmware',type=Path);p.add_argument('helper',type=Path)
    p.add_argument('--output',type=Path,default=HERE/'ble-calibration-bundled.js')
    p.add_argument('--version',default='development BLE build')
    args=p.parse_args();write_bundle(args.output,args.firmware,args.helper,args.version)
    print('Bundled radio recovery: '+str(args.output))
